import { useEffect, useState } from "react";
import { call, ApiError, type ProblemDetails } from "../../api/client.js";
import { loadMe, type Me } from "../login/me.js";
import { yuan, days } from "../cost/money.js";
import { daysSince } from "../../shell/dates.js";

/* ════════════════════════════════════════════════════════════════════
   待我审批。

   ── 它和「工时与差旅」不是一回事 ──────────────────────────────────
   那一页是**全量台账**：谁在什么时候填了什么、值多少钱、作废了没有。
   这一页只有一件事：**现在等我点头的是哪几条。**

   同一批数据两种切法。台账每月对账时看，这一页每天开工前看 ——
   把后者做成前者的一个筛选项，人就得先想起来去勾那个筛选。

   ── 三条规则写在页面上，因为它们经常被误解 ────────────────────────
   ① **审批不改变任何金额。** 人已经干了活，成本已经发生（见迁移 0023）。
      它只回答一个问题：这笔工时有没有被第二个人看过。
   ② **不能审自己填的。** 自审等于没有审批流，只是多了一次点击 ——
      而多出来的那次点击会让人以为这里已经有把关了。这条在库里。
   ③ **审过不能撤回。** 审错了要作废这一笔再重报 ——
      能撤回的审批痕迹等于没有审批痕迹。
   ════════════════════════════════════════════════════════════════════ */

interface Entry {
  id: string; studySiteId: string; siteCode: string;
  accountId: string; personName: string;
  workDate: string; workType: string; workTypeLabel: string;
  billable: boolean; hours: number;
  costCents?: number; travelCents?: number;
  subjectId: string | null; visitId: string | null;
  autoGenerated: boolean; note: string | null;
  voidedAt: string | null;
  approvedAt: string | null; approvedByName: string | null;
}

export function ApprovalsPage() {
  const [me, setMe] = useState<Me | null>(null);
  const [rows, setRows] = useState<Entry[] | null>(null);
  const [problem, setProblem] = useState<ProblemDetails | null>(null);
  const [said, setSaid] = useState<string | null>(null);
  const [busy, setBusy] = useState<string | null>(null);

  const reload = () =>
    call<{ items: Entry[] }>("listTimesheets",
      { query: { limit: 200, unapprovedOnly: true } })
      .then(r => setRows(r.items));

  useEffect(() => { void loadMe().then(setMe); void reload(); }, []);

  if (!me || !rows) return <p className="muted">加载中…</p>;

  if (!me.permissions.actions.includes("approve")) return (
    <>
      <div className="page-head"><h2>待我审批</h2></div>
      <p className="problem" data-testid="approve-forbidden">
        你的角色（{me.account.role.name}）没有「审批工时 / 差旅 / 偏离」这个动作。
        这一页对你是空的 —— 不是没有待审的，是它们不归你审。
      </p>
    </>
  );

  /* **自己填的不出现在这里。** 服务端会拒（迁移 0023 的 CHECK），
     列在这里只会让人点一下再拿一个 422。 */
  const mine = rows.filter(t => t.accountId === me.account.id);
  const todo = rows.filter(t => t.accountId !== me.account.id);
  const showCost = todo.some(t => t.costCents !== undefined);
  const total = todo.reduce((n, t) => n + (t.costCents ?? 0), 0);
  const stale = todo.filter(t => daysSince(t.workDate) > 30);

  const approve = async (t: Entry) => {
    setBusy(t.id); setProblem(null); setSaid(null);
    try {
      await call("approveTimesheet", { params: { id: t.id }, body: {} });
      await reload();
      setSaid(`已审 ${t.personName} ${t.workDate} 的 ${t.workTypeLabel}`);
    } catch (e) {
      if (e instanceof ApiError) setProblem(e.problem); else throw e;
    } finally { setBusy(null); }
  };

  return (
    <>
      <div className="page-head">
        <h2>待我审批</h2>
        <p data-testid="approve-summary">
          {todo.length === 0
            ? "没有等你的。"
            : <>{todo.length} 条工时等着第二个人看
                {showCost && <>，合计 <b>{yuan(total)}</b></>}
                {stale.length > 0 && <>，其中 <b>{stale.length} 条超过 30 天</b></>}。</>}
        </p>
      </div>

      <div className="derive" style={{ marginBottom: 14 }}>
        <b>审批不改变任何金额。</b> 人已经干了活，成本已经发生 ——
        它只回答一个问题：这笔工时<b>有没有被第二个人看过</b>。
        所以待审的钱**已经在损益里**了；这个数一直不降说明审批积压，
        不是成本失控。
      </div>

      {mine.length > 0 && (
        <div className="problem" data-testid="own-entries" style={{ marginBottom: 14 }}>
          你自己还有 {mine.length} 条没被审 —— <b>它们不在下面这张表里</b>。
          自审等于没有审批流，只是多了一次点击，
          而多出来的那次点击会让人以为这里已经有把关了。这条规则在数据库里。
        </div>
      )}

      {problem && (
        <div className="problem stack" data-testid="approve-problem" style={{ marginBottom: 12 }}>
          <strong>{problem.title}</strong>
          {problem.detail && <div>{problem.detail}</div>}
        </div>
      )}
      {said && <p className="muted" data-testid="approve-said">{said}</p>}

      {todo.length === 0 ? (
        <p className="muted" data-testid="approve-empty">
          都审完了。<b>这一页空着是好事</b> —— 它只列等你点头的，
          全量台账在「工时与差旅」。
        </p>
      ) : (
        <div className="table-wrap">
          <table>
            <thead>
              <tr>
                <th>填报人</th><th>日期</th><th>中心</th><th>工作</th>
                <th className="num">工时</th>
                {showCost && <th className="num">成本</th>}
                <th>来源</th><th>说明</th><th />
              </tr>
            </thead>
            <tbody>
              {[...todo]
                /* 最久的排最前 —— 一条挂了两个月的工时，
                   填的人早就忘了当时做了什么，审也审不出什么。 */
                .sort((a, b) => a.workDate.localeCompare(b.workDate))
                .map(t => {
                  const age = daysSince(t.workDate);
                  return (
                    <tr key={t.id} data-testid="approve-row">
                      <td>{t.personName}</td>
                      <td>
                        <span className="mono muted">{t.workDate}</span>
                        {age > 30 && <span className="chip warn" style={{ marginLeft: 6 }}>
                          {age} 天前
                        </span>}
                      </td>
                      <td className="mono">{t.siteCode}</td>
                      <td>
                        {t.workTypeLabel}
                        {!t.billable && <span className="chip flat" style={{ marginLeft: 6 }}>
                          不可计费
                        </span>}
                      </td>
                      <td className="num">{days(t.hours)}</td>
                      {showCost && <td className="num">{yuan(t.costCents ?? 0)}</td>}
                      <td className="muted">
                        {/* 自动生成的那些是访视完成时系统记的 ——
                            它们同样要人看过，但看的是"这次访视真做了吗"，
                            不是"这个人填得对不对"。 */}
                        {t.autoGenerated ? "完成访视自动生成" : "手工填报"}
                      </td>
                      <td className="muted">{t.note ?? "—"}</td>
                      <td>
                        <button className="btn primary" data-testid={`approve-${t.id}`}
                          disabled={busy === t.id}
                          onClick={() => void approve(t)}>
                          {busy === t.id ? "…" : "我看过了"}
                        </button>
                      </td>
                    </tr>
                  );
                })}
            </tbody>
          </table>
        </div>
      )}

      <div className="derive" style={{ marginTop: 14 }}>
        按日期升序 —— <b>最久的排最前</b>。一条挂了两个月的工时，
        填的人早就忘了当时做了什么，那时再审也审不出什么。
        <br />
        <b>审过不能撤回。</b> 审错了要作废这一笔再重报 ——
        能撤回的审批痕迹等于没有审批痕迹。所以这个按钮写的是「我看过了」，
        不是「通过」：它陈述的是一件已经发生的事。
      </div>
    </>
  );
}
