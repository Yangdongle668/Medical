/* ══════════════════════════════════════════════════════════════════
   这一份构建是**演示台**还是**生产台**。

   ── 为什么要有这个判断 ──────────────────────────────────────────
   演示台和生产台如果长得一模一样，会同时出两种误会，而且都不便宜：

     · 看演示的人以为那是生产系统 —— 于是拿演示数据去开会，
       "我们有 3 个中心在入组"这句话就带着假前提传下去了；
     · 登进生产的人以为自己还在演示里 —— 于是当真去点那些按钮。

   所以登录页要**第一眼说清这是哪一套**。判据用构建期开关，
   和 main.tsx 决定要不要装 msw 的是同一个：

     · `VITE_USE_MOCKS=1`（`npm run build:mock`）→ 演示；
     · `import.meta.env.DEV`（本机 dev server）→ 演示；
     · 其余（`npm run build`，也就是部署进容器的那一份）→ 生产。

   **不能靠域名或运行时探测。** 那两种都能在演示环境里被配成生产的样子，
   而这个判断的全部价值就在于它不可能配错：mock 数据和"演示"这两件事
   由同一个开关决定，它们不可能分开。
   ══════════════════════════════════════════════════════════════════ */

/** 这一份构建带着 mock 数据 —— 也就是演示台。 */
export const IS_DEMO: boolean =
  import.meta.env.DEV || import.meta.env.VITE_USE_MOCKS === "1";
