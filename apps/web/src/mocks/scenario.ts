/* ════════════════════════════════════════════════════════════════════
   一条业务流的 mock 场景 —— **有状态的，不是一堆固定响应。**

   契约生成的 examples.json 覆盖面全，但每个响应各自随机，
   拼不成一条连贯的流程：勾掉的任务下一次请求又是未勾的，
   完成访视后不会真的排出下一次。那种 mock 能验证「页面画得出来」，
   验证不了「这条流程走得通」—— 而后者才是 Phase 5 的退出标准。

   所以这里给**一份内存状态**，只覆盖 CRC 每天真正要走的那条路：
   看今天到期的 → 打开一例 → 逐项勾任务 → 完成访视 → 看到一串后果。

   数据取自原型（吴桐 / SS-01 北京协和 / S-0203），与种子同源。
   ════════════════════════════════════════════════════════════════════ */

export interface MockTask { seq: number; task: string; doneAt: string | null }

export interface MockVisit {
  id: string; subjectId: string; screeningNo: string;
  studySiteId: string; siteCode: string; seq: number;
  visitCode: string; visitLabel: string;
  targetDate: string; windowDays: number; windowFrom: string; windowTo: string;
  actualDate: string | null; status: string; edcStatus: string;
  edcDaysLate: number | null; outOfWindow: boolean; daysLeft: number | null;
  piConfirmedAt: string | null; piConfirmedByName: string | null;
  tasks: MockTask[];
}

const iso = (d: Date) => d.toISOString().slice(0, 10);
const shift = (base: Date, n: number) => {
  const d = new Date(base); d.setDate(d.getDate() + n); return iso(d);
};
const TODAY = new Date();

const SITES = [
  { id: "s1", code: "SS-01", hospital: "北京协和医院", state: "enrolling" },
  { id: "s2", code: "SS-07", hospital: "中山大学肿瘤防治中心", state: "enrolling" }
];

/** 每例的任务清单来自项目的 SOA —— 与 visit_template_task 同一套文字 */
const TASKS_ONCO = [
  "生命体征与体格检查",
  "血常规 + 生化采血（空腹）",
  "ECOG 体能评分记录",
  "研究药物发放与既往剩余回收清点",
  "合并用药与不良事件问询"
];
const TASKS_IO = [
  "生命体征与体格检查",
  "采血与样本离心送检（2 小时内）",
  "免疫相关不良事件专项问询",
  "研究药物配制核对与输注陪同"
];

function mkVisit(
  id: string, site: typeof SITES[number], screeningNo: string, subjectId: string,
  seq: number, label: string, dueIn: number, win: number, tasks: string[],
  doneCount = 0
): MockVisit {
  const target = shift(TODAY, dueIn);
  return {
    id, subjectId, screeningNo, studySiteId: site.id, siteCode: site.code, seq,
    visitCode: `V-${seq}`, visitLabel: label,
    targetDate: target, windowDays: win,
    windowFrom: shift(new Date(target), -win), windowTo: shift(new Date(target), win),
    actualDate: null, status: "planned", edcStatus: "pending",
    edcDaysLate: null, outOfWindow: dueIn + win < 0, daysLeft: dueIn + win,
    piConfirmedAt: null, piConfirmedByName: null,
    tasks: tasks.map((t, i) => ({
      seq: i, task: t, doneAt: i < doneCount ? new Date().toISOString() : null }))
  };
}

/** 可变状态。每次 resetScenario() 回到已知起点 —— 测试要从确定处出发。 */
export interface Scenario {
  visits: MockVisit[];
  /** 完成访视时累积产生的质量事件，供台账页读取 */
  qualityEvents: {
    id: string; code: string; siteCode: string; kind: string; severity: string;
    state: string; title: string; detail: string; autoGenerated: boolean;
    raisedBy: string; raisedOn: string; ageDays: number;
  }[];
  timesheets: { id: string; siteCode: string; workDate: string; hours: number }[];
}

export function makeScenario(): Scenario {
  return {
    visits: [
      /* 已超窗 3 天 —— 列表第一屏就该看见它 */
      mkVisit("v1", SITES[0]!, "S-0331", "u1", 4, "C4D1 第 4 周期给药",
        -6, 3, TASKS_ONCO, 2),
      /* 今天到期 */
      mkVisit("v2", SITES[0]!, "S-0203", "u2", 8, "C8D1 第 8 周期给药",
        0, 3, TASKS_ONCO, 3),
      /* 窗口内，还有 2 天 */
      mkVisit("v3", SITES[1]!, "S-0224", "u3", 3, "C3D1 给药 + 肿瘤评估",
        2, 2, TASKS_IO, 0),
      /* 下周 */
      mkVisit("v4", SITES[1]!, "S-0198", "u4", 12, "C12D1 第 12 周期给药",
        7, 3, TASKS_IO, 0)
    ],
    qualityEvents: [],
    timesheets: []
  };
}

