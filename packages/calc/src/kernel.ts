/* ════════════════════════════════════════════════════════════════════
   计算引擎 —— 口径的唯一实现。

   为什么必须独立成一层：原型阶段踩过一次。「SAE 24h 及时率」和
   「Query 平均关闭天数」是写死的常量，而同一个页面下方就摆着一条
   超窗的 SAE。演示时没人看得出来，真实系统里这就是**看板骗人** ——
   而质量看板骗人，是要到药监核查时才付账的。

   三条规矩：
     ① 界面上出现的每一个业务数字都来自这里，且带口径版本号；
     ② 这里是纯函数，不碰 IO —— 前后端共用同一份实现（架构断言强制）；
     ③ 金额一律**整数分**。四则运算里出现一次浮点，对账就永远差几分钱。
   ════════════════════════════════════════════════════════════════════ */

/** 口径版本。**改了任何一条算法都要动它** —— 报表上要能标出「按哪版口径算的」。
 *  历史报表不会因为口径升级而变化：算过的数带着版本号存下来。 */
export const CALC_VERSION = "2026.1";

/** 一个人天等于几小时。它是口径的一部分，不是常识 ——
 *  按 7.5 还是 8 小时折算，单例成本会差 6%，而 6% 足以让一个中心从盈利变亏损。 */
export const HOURS_PER_DAY = 8;

/** 分。整数。 */
export type Cents = number;

/** 四舍五入到整数分。**所有除法的出口都必须经过它。**
 *
 *  两处细节，都不是洁癖：
 *  ① JS 的 Math.round 对 −0.5 取 0（向上），会让冲销记录比原记录少一分钱。
 *     这里对负数按绝对值取整再还原符号，保证 f(−x) === −f(x)。
 *  ② `+ 0` 把 −0 归一成 0。−0 序列化成 JSON 是 0，看不出来，
 *     但 Object.is(−0, 0) 是 false —— 断言、去重、Map 键都会踩到，
 *     而排查时会发现「明明都是 0 却不相等」。 */
export const roundCents = (v: number): Cents =>
  (v < 0 ? -Math.round(-v) : Math.round(v)) + 0;

/** 比率保护：分母为 0 时返回 null，而不是 0 或 NaN。
 *  「没有分母」和「比率是 0」是两回事 —— 前者该显示「—」，后者该显示「0%」。 */
export const ratio = (num: number, den: number): number | null =>
  den > 0 ? num / den : null;
